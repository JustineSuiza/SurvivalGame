export function iconSVG(id) {
  const it = ITEMS[id];
  if (!it) return "";
  const fn = SHAPES[it.shape] || SHAPES.stone;
  return fn(it.color);
}

export function slotAccepts(slot, id) {
  const it = ITEMS[id];
  return !!it && it.slot === slot;
}
